def main():
    base = sys.argv[1] if len(sys.argv) > 1 else "i18n"
    expected = set(NEW["en"].keys())
    for lang, strings in NEW.items():
        assert set(strings.keys()) == expected, f"{lang} key mismatch"
        path = os.path.join(base, lang + ".json")
        # object_pairs_hook preserves the hand-grouped key order of the
        # catalog; new keys are APPENDED, never re-sorted (D-044 style:
        # keep the diff reviewable).
        doc = json.load(open(path, encoding="utf-8"),
                        object_pairs_hook=collections.OrderedDict)
        added = 0
        for k, v in strings.items():
            if k not in doc["strings"]:
                doc["strings"][k] = v
                added += 1
        with open(path, "w", encoding="utf-8") as f:
            json.dump(doc, f, ensure_ascii=False, indent=2)
            f.write("\n")
        print(f"{lang}: +{added} (total {len(doc['strings'])})")

if __name__ == "__main__":
    main()
